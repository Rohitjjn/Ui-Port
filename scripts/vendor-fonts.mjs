#!/usr/bin/env node
/**
 * One source of truth for the font files the reference capture and the Compose port both use.
 *
 *   node scripts/vendor-fonts.mjs            # copy res/font into every mirror
 *   node scripts/vendor-fonts.mjs --check    # verify every mirror is byte-identical, exit 8 if not
 *
 * Why this exists: the capture blocks all off-origin requests, so the prototype's Google Fonts
 * stylesheet never loaded and the reference was rendered with the browser's *fallback* stacks,
 * while the Compose side used the unbundled `FontFamily.Serif`/`SansSerif`. Two different
 * typefaces were being compared and every text measurement was noise.
 *
 * The fingerprint check is the enforcement: if either side's copy drifts by one byte, the two
 * rasterisers are drawing different outlines and no pixel score is trustworthy.
 *
 * Exit codes: 0 ok, 2 usage/config error, 8 drift detected (--check).
 */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { checkMirrors, defaultFontConfigPath, fontFaceCss, loadFontConfig, requiredFiles } from "./lib/fonts.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const at = args.indexOf("--config");
const configFile = at === -1 ? defaultFontConfigPath() : path.resolve(args[at + 1] ?? "");

let config;
try {
  config = loadFontConfig(configFile);
} catch (err) {
  process.stderr.write(`vendor-fonts: ${err.message}\n`);
  process.exit(2);
}

const sourceDir = path.resolve(ROOT, config.sources.directory);
const mirrors = (config.sources.mirrors ?? []).map((m) => path.resolve(ROOT, m));
const required = requiredFiles(config);

if (!check) {
  const problems = checkMirrors({ ...config, sources: { ...config.sources, mirrors: [] } }, ROOT);
  if (problems.length) {
    process.stderr.write(
      `vendor-fonts: ${config.sources.directory} is missing ${problems.map((p) => p.file).join(", ")}\n` +
        "  These are the canonical files the manifest declares; a capture cannot run without them.\n",
    );
    process.exit(2);
  }
  for (const dir of mirrors) {
    fs.mkdirSync(dir, { recursive: true });
    for (const f of required) fs.copyFileSync(path.join(sourceDir, f), path.join(dir, f));
  }
  // The generated stylesheet is written into the source directory so the prototype's static
  // server, the capture (which serves it itself) and the mirrors all see the same rules.
  const cssFile = path.join(sourceDir, "uiport-fonts.css");
  fs.writeFileSync(cssFile, `/* generated by scripts/vendor-fonts.mjs -- do not edit */\n${fontFaceCss(config)}\n`);
  process.stdout.write(`vendor-fonts: copied ${required.length} file(s) to ${mirrors.length} mirror(s), wrote ${path.relative(ROOT, cssFile)}\n`);
} else {
  const problems = checkMirrors(config, ROOT);
  if (problems.length) {
    process.stderr.write(`vendor-fonts: ${problems.length} problem(s) against ${config.sources.directory}\n`);
    for (const p of problems) {
      process.stderr.write(`  ${p.problem}: ${path.relative(ROOT, path.join(p.dir, p.file))}${p.expected ? ` (expected ${p.expected.slice(0, 12)}, got ${String(p.actual).slice(0, 12)})` : ""}\n`);
    }
    process.stderr.write("  Run `node scripts/vendor-fonts.mjs`. Comparing two different font files measures the fonts, not the port.\n");
    process.exit(8);
  }
  process.stdout.write(`vendor-fonts: ${required.length} file(s) match across ${mirrors.length} mirror(s)\n`);
  for (const f of required) process.stdout.write(`  ${f}\n`);
}
